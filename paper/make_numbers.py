"""Import every number, generated table and figure of the two studies into the combined paper.

    python3 paper/make_numbers.py           write paper/generated/ and paper/figures/
    python3 paper/make_numbers.py --check   recompute them in memory and compare with the files on disk

Nothing is computed here. Each study's own paper/make_numbers.py generates its macros and tables from its saved
outputs (study-1-first-order/ and study-2-causes/; their quick checks recompute them). This script copies them:

- paper/generated/numbers.tex: the union of the two studies' macros. A macro that both studies define must have the
  same value in both and is written once; any macro with two different values stops the script. No macro is renamed.
  CROSS_STUDY lists quantities that the two studies name differently and that must agree, because Study 2 recomputed
  Study 1's reference; they are compared here too.
- paper/generated/s1-*.tex and s2-*.tex: the generated table bodies, byte for byte.
- paper/figures/s1-*.pdf and s2-*.pdf: the figures the paper uses, byte for byte (Study 2's strength figure is not
  used; its numbers are in the paper's Appendix D).
- paper/generated/import-record.json: where every macro, table and figure came from.
paper/references.bib is shipped as written: the union of the two studies' bibliographies without the two entries in
which each cited the other.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent
ROOT = PAPER.parent
STUDY = {"1": ROOT / "study-1-first-order/paper", "2": ROOT / "study-2-causes/paper"}
FIGURES = {
    "s1-fig1-screening.pdf": ("1", "figures/fig1-screening.pdf"),
    "s1-fig2-predicted-vs-exact.pdf": ("1", "figures/fig2-predicted-vs-exact.pdf"),
    "s1-fig3-model-errors.pdf": ("1", "figures/fig3-model-errors.pdf"),
    "s1-fig4-strength.pdf": ("1", "figures/fig4-strength.pdf"),
    "s2-fig1-error-ratios.pdf": ("2", "figures/fig1-error-ratios.pdf"),
    "s2-fig2-predicted-vs-exact.pdf": ("2", "figures/fig2-predicted-vs-exact.pdf"),
    "s2-fig3-per-model.pdf": ("2", "figures/fig3-per-model.pdf"),
}
# (Study 1 macro, Study 2 macro): the same quantity under two names.
CROSS_STUDY = [
    ("MaeFOFull", "MaeRefFull"), ("MaeZeroFull", "MaeZeroRefFull"), ("PrecFOFull", "TopTenRefFull"),
    ("PrecAnatFull", "AnatRefFull"), ("WrongSignFull", "WrongRefFull"), ("MainCasesFull", "NCasesFull"),
    ("MainCasesFull", "PostCases"), ("LargeFull", "NLargeFull"), ("MainReadouts", "NUnitsEligible"),
    ("ReadoutConditions", "NUnitsAll"), ("NetNodes", "NodesFlyVis"), ("NetTypes", "NTypes"),
    ("NetEdges", "EdgesFlyVis"), ("MainDSI", "SelThreshold"), ("SimulatedTypes", "NSimTypes"),
    ("TimeExactFull", "TimeExactAIsix"), ("TimeGradient", "TimeDerivAIsix"), ("BootstrapReps", "BootReps"),
]
DEFINITION = re.compile(r"^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}$")


def macros(study):
    found = {}
    for line in (STUDY[study] / "generated/numbers.tex").read_text().splitlines():
        if not line.strip() or line.startswith("%"):
            continue
        match = DEFINITION.match(line)
        if not match:
            sys.exit(f"Study {study}: unexpected line in generated/numbers.tex: {line[:80]}")
        name, value = match.groups()
        if name in found:
            sys.exit(f"Study {study} defines \\{name} twice")
        found[name] = value
    return found


def build():
    out = {}
    record = {"macros": {}, "tables": {}, "figures": {}, "cross_study": []}
    m1, m2 = macros("1"), macros("2")
    clashes = sorted(n for n in set(m1) & set(m2) if m1[n] != m2[n])
    if clashes:
        sys.exit("macros with different values in the two studies: " + ", ".join(clashes))
    lines = ["% Generated by paper/make_numbers.py: the union of the two studies' generated/numbers.tex. Do not edit.",
             "% Study 1 = study-1-first-order, Study 2 = study-2-causes.",
             "% Macros defined by both studies, with the same value: "
             + ", ".join(sorted(set(m1) & set(m2))) + "."]
    for name in sorted(set(m1) | set(m2)):
        value = m1.get(name, m2.get(name))
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
        record["macros"][name] = {"value": value, "study": "both" if name in m1 and name in m2 else
                                  ("1" if name in m1 else "2")}
    out["generated/numbers.tex"] = "\n".join(lines) + "\n"
    for one, two in CROSS_STUDY:
        if m1[one] != m2[two]:
            sys.exit(f"Study 1's \\{one} = {m1[one]} but Study 2's \\{two} = {m2[two]}")
        record["cross_study"].append({"study1": one, "study2": two, "value": m1[one]})
    for study in ("1", "2"):
        for table in sorted((STUDY[study] / "generated").glob("table-*.tex")):
            name = f"generated/s{study}-{table.name}"
            out[name] = table.read_bytes()
            record["tables"][name] = {"study": study, "from": f"paper/generated/{table.name}",
                                      "sha256": hashlib.sha256(out[name]).hexdigest()}
    for name, (study, source) in FIGURES.items():
        out[f"figures/{name}"] = (STUDY[study] / source).read_bytes()
        record["figures"][name] = {"study": study, "from": f"paper/{source}",
                                   "sha256": hashlib.sha256(out[f"figures/{name}"]).hexdigest()}
    out["generated/import-record.json"] = json.dumps(record, indent=1, ensure_ascii=False) + "\n"
    return out


def as_bytes(content):
    return content if isinstance(content, bytes) else content.encode()


def main():
    out = build()
    if "--check" in sys.argv:
        problems = [name for name, content in out.items()
                    if not (PAPER / name).exists() or (PAPER / name).read_bytes() != as_bytes(content)]
        stray = [str(p.relative_to(PAPER)) for folder in ("generated", "figures") for p in (PAPER / folder).iterdir()
                 if str(p.relative_to(PAPER)) not in out]
        for name in problems:
            print(f"FAIL: paper/{name} differs from what the two studies' files give")
        for name in stray:
            print(f"FAIL: paper/{name} is not produced by make_numbers.py")
        if problems or stray:
            sys.exit(1)
        record = json.loads(out["generated/import-record.json"])
        print(f"paper/make_numbers.py --check: {len(record['macros'])} macros, {len(record['tables'])} tables and "
              f"{len(record['figures'])} figures match the two studies' files; "
              f"{len(record['cross_study'])} cross-study quantities agree")
        return
    for name, content in out.items():
        (PAPER / name).parent.mkdir(parents=True, exist_ok=True)
        (PAPER / name).write_bytes(as_bytes(content))
    print(f"wrote {len(out)} files")


if __name__ == "__main__":
    main()
